package tools.aqua.stars.coverage.significance.db.repositories

import java.util.UUID
import org.jetbrains.exposed.sql.ResultRow
import org.jetbrains.exposed.sql.and
import org.jetbrains.exposed.sql.batchInsert
import org.jetbrains.exposed.sql.insertIgnore
import tools.aqua.stars.coverage.significance.db.dataclasses.MetricTotalTickDifferenceEntry
import tools.aqua.stars.coverage.significance.db.db
import tools.aqua.stars.coverage.significance.db.tables.MetricTotalTickDifferenceTable
import tools.aqua.stars.coverage.significance.db.tables.MetricTotalTickDifferenceTable.mutant
import tools.aqua.stars.coverage.significance.db.tables.MetricTotalTickDifferenceTable.run
import tools.aqua.stars.coverage.significance.db.tables.MetricTotalTickDifferenceTable.startingScenarioConfiguration
import tools.aqua.stars.coverage.significance.db.tables.MetricTotalTickDifferenceTable.totalTickDifferenceMillis

/**
 * Repository for accessing and modifying entries in the [MetricTotalTickDifferenceTable]. Provides
 * methods for batch inserting entries and inserting an entry if it is missing, returning the ID of
 * the inserted or existing entry.
 */
object MetricTotalTickDifferenceRepository {

  /**
   * Batch inserts the given list of [MetricTotalTickDifferenceEntry]s into the
   * [MetricTotalTickDifferenceTable].
   *
   * @param entries The list of [MetricTotalTickDifferenceEntry]s to insert. The `id` field of each
   *   entry is ignored, as it will be generated by the database.
   * @return The list of [ResultRow]s of the inserted entries, in the same order as the input list.
   *   Each ID corresponds to the entry at the same index in the input list.
   */
  fun batchInsert(entries: List<MetricTotalTickDifferenceEntry>): List<ResultRow> = db {
    MetricTotalTickDifferenceTable.batchInsert(entries) { entry ->
      this[run] = entry.runId
      this[startingScenarioConfiguration] = entry.scenarioConfigId
      this[mutant] = entry.mutantId
      this[totalTickDifferenceMillis] = entry.totalTickDifferenceMillis
    }
  }

  /**
   * Inserts the given [MetricTotalTickDifferenceEntry] into the [MetricTotalTickDifferenceTable] if
   * an entry with the same TSC ID, run ID, scenario configuration ID, and mutant ID does not
   * already exist. Returns the ID of the inserted entry, or the ID of the existing entry if it
   * already exists.
   *
   * @param entry The [MetricTotalTickDifferenceEntry] to insert. The `id` field of the entry must
   *   be null, as it will be generated by the database.
   * @return The ID of the inserted entry, or the ID of the existing entry if an entry with the same
   *   TSC ID, run ID, scenario configuration ID, and mutant ID already exists in the database.
   */
  fun insertIfMissingAndReturnId(entry: MetricTotalTickDifferenceEntry): UUID = db {
    require(entry.id == null) { "insertIfMissingAndReturnId() expects entry.id == null." }

    MetricTotalTickDifferenceTable.insertIgnore { row ->
      row[run] = entry.runId
      row[startingScenarioConfiguration] = entry.scenarioConfigId
      row[mutant] = entry.mutantId
      row[totalTickDifferenceMillis] = entry.totalTickDifferenceMillis
    }

    MetricTotalTickDifferenceTable.select(MetricTotalTickDifferenceTable.id)
        .where {
          (run eq entry.runId) and
              (startingScenarioConfiguration eq entry.scenarioConfigId) and
              (mutant eq entry.mutantId)
        }
        .limit(1)
        .single()[MetricTotalTickDifferenceTable.id]
        .value
  }
}
